import { execFileSync } from 'node:child_process'
import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'
const run=(...args)=>execFileSync('/home/clachance14/.claude/skills/gstack/browse/dist/browse',args,{env:{...process.env,BROWSE_STATE_FILE:'/tmp/tinesight-photos-ui-browser/browse.json'},encoding:'utf8'}).trim()
const js=code=>run('js',code)
const pause=()=>new Promise(r=>setTimeout(r,120))
const select=()=>js(`window.zoomEl=[...document.querySelectorAll('[data-photo-viewport]')].find(e=>e.clientWidth>0&&!e.closest('[inert]'));window.zoomEl.focus()`)
const scale=()=>Number(js('window.zoomEl.dataset.zoomScale'))
const evidence=[]
run('viewport','1280x800');select()
js(`window.zoomBefore={url:location.href,header:document.querySelector('header').getBoundingClientRect().height,page:document.querySelector('main').scrollTop};const r=window.zoomEl.getBoundingClientRect();window.zoomEl.dispatchEvent(new WheelEvent('wheel',{deltaY:-250,clientX:r.left+r.width/2,clientY:r.top+r.height/2,bubbles:true,cancelable:true}))`)
await pause();assert(scale()>1)
assert(js('location.href===window.zoomBefore.url&&document.querySelector("header").getBoundingClientRect().height===window.zoomBefore.header&&document.querySelector("main").scrollTop===window.zoomBefore.page')==='true')
assert(!run('snapshot','-i').includes('Zoom in on photo'))
evidence.push({check:'wheel zoom changes photo only, page position and route unchanged',scale:scale()})
run('press','ArrowRight');await pause();assert(js('window.zoomEl.querySelector("[data-photo-transform]").style.transform').includes('translate(-40px'))
run('screenshot','.gstack/triage-runs/photos-ui/inline-zoom-desktop.png')
run('press','Escape');await pause();assert.equal(scale(),1)
js(`const r=window.zoomEl.getBoundingClientRect();window.zoomEl.dispatchEvent(new MouseEvent('dblclick',{bubbles:true,cancelable:true,clientX:r.left+r.width/2,clientY:r.top+r.height/2}))`)
await pause();assert.equal(scale(),2.5);run('press','Escape')
evidence.push({check:'keyboard pan, Escape reset, double-click zoom'})
run('viewport','390x844');select()
js(`window.zoomTouch=(type,points)=>{const r=window.zoomEl.getBoundingClientRect();const ts=points.map(([x,y],i)=>new Touch({identifier:i,target:window.zoomEl,clientX:r.left+x,clientY:r.top+y}));window.zoomEl.dispatchEvent(new TouchEvent(type,{bubbles:true,cancelable:true,touches:type==='touchend'?[]:ts,targetTouches:type==='touchend'?[]:ts,changedTouches:ts}))};window.zoomUrl=location.href;window.zoomTouch('touchstart',[[120,200]])`)
await pause();js(`window.zoomTouch('touchstart',[[120,200],[220,200]])`)
await pause();js(`window.zoomTouch('touchmove',[[60,200],[280,200]])`)
await pause();js(`window.zoomTouch('touchend',[[60,200],[280,200]])`)
await pause();assert(scale()>2);assert.equal(js('location.href===window.zoomUrl'),'true')
const before=js('window.zoomEl.querySelector("[data-photo-transform]").style.transform')
js(`window.zoomTouch('touchstart',[[180,220]])`);await pause();js(`window.zoomTouch('touchmove',[[100,260]])`);await pause();js(`window.zoomTouch('touchend',[[100,260]])`);await pause()
assert.notEqual(js('window.zoomEl.querySelector("[data-photo-transform]").style.transform'),before)
assert.equal(js('location.href===window.zoomUrl'),'true')
assert.equal(Number(js('visualViewport.scale')),1)
run('screenshot','.gstack/triage-runs/photos-ui/inline-zoom-mobile.png')
evidence.push({check:'pinch then one-finger pan stay on current photo, browser viewport scale stays 1',scale:scale()})
select();run('press','Escape');await pause();assert.equal(scale(),1)
assert.equal(js(`[...document.querySelectorAll('[data-photo-viewport] img')].every(e=>e.src.includes('/medium/'))`),'true')
js(`window.zoomTouch('touchstart',[[160,200]]);window.zoomTouch('touchend',[[160,200]])`)
await pause();js(`window.zoomTouch('touchstart',[[160,200]]);window.zoomTouch('touchend',[[160,200]])`)
await pause();assert.equal(scale(),2.5)
js(`document.querySelector('a[aria-label="Next photo"]').click()`)
for(let n=0;n<50;n++){await pause();if(js('location.href!==window.zoomUrl')==='true')break}
select();assert.equal(scale(),1)
evidence.push({check:'double-tap zoom and navigating to next photo resets magnification'})
await writeFile('.gstack/triage-runs/photos-ui/zoom-acceptance.json',JSON.stringify(evidence,null,2)+'\n')
console.log('PASS inline zoom acceptance',JSON.stringify(evidence))
